"""Step 27 (F1): UIDocument -> a runnable Vite + React + Tailwind project, zipped.

Each screen becomes src/screens/<Name>.jsx; arrows become hash links (#/name) that App.jsx routes,
so the project needs only react, react-dom and vite.

    unzip sketch2ui-app.zip && cd sketch2ui-app && npm install && npm run dev
"""
import io
import json
import re
import zipfile

from app.schemas.component_schema import UIDocument
from app.services.codegen_service import BODY_CLASS, MAIN_CLASS, RUNTIME, TAILWIND, _Renderer, navs, page_name

VOID = ("input", "img")


def component_name(screen_name: str, used: set) -> str:
    base = "".join(w.capitalize() for w in re.findall(r"[A-Za-z0-9]+", screen_name)) or "Screen"
    if base[0].isdigit():
        base = "Screen" + base
    name, n = base, 2
    while name in used:
        name, n = f"{base}{n}", n + 1
    used.add(name)
    return name


def html_to_jsx(html: str) -> str:
    jsx = html.replace("{", "&#123;").replace("}", "&#125;")
    jsx = jsx.replace(' class="', ' className="').replace(' for="', ' htmlFor="')
    jsx = re.sub(r" checked(?=[ >])", " defaultChecked", jsx)
    jsx = re.sub(r" (stroke|fill|vector)-([a-z]+)=", lambda m: f" {m.group(1)}{m.group(2).capitalize()}=", jsx)  # SVG attrs
    jsx = re.sub(r" (data-fav)(?=[ >])", r' \1=""', jsx)
    jsx = re.sub(r' value="(\d+)"', r' defaultValue="\1"', jsx)
    jsx = re.sub(rf"<({'|'.join(VOID)})\b([^>]*?)\s*>", r"<\1\2 />", jsx)
    jsx = re.sub(r'(href|data-next)="([a-z0-9-]+)\.html"',
                 lambda m: f'{m.group(1)}="#/{"" if m.group(2) == "index" else m.group(2)}"', jsx)
    return jsx


def build_project(doc: UIDocument, app_name: str = "sketch2ui-app") -> dict[str, str]:
    files = {s.id: page_name(s, i) for i, s in enumerate(doc.screens)}
    used: set = set()
    screens = []  # (component, route)
    out: dict[str, str] = {}
    nav = navs(doc)

    for i, screen in enumerate(doc.screens):
        comp = component_name(screen.name, used)
        route = "" if i == 0 else files[screen.id].removesuffix(".html")
        link_to = {l.fromComponent: files[l.toScreen] for l in doc.links if l.fromScreen == screen.id}
        renderer = _Renderer(link_to, nav[screen.id])
        body = "\n".join(html_to_jsx(renderer.render(k, 3)) for k in screen.root.children)
        out[f"src/screens/{comp}.jsx"] = (
            f"export default function {comp}() {{\n  return (\n"
            f'    <main className="{MAIN_CLASS}">\n'
            f"{body}\n    </main>\n  );\n}}\n")
        screens.append((comp, route))

    imports = "".join(f'import {c} from "./screens/{c}.jsx";\n' for c, _ in screens)
    routes = ",\n".join(f'  "{r}": {c}' for c, r in screens)
    out["src/App.jsx"] = f"""import {{ useEffect, useState }} from "react";
{imports}
// One entry per drawn screen; arrows in the sketch link between them with #/route
const routes = {{
{routes}
}};

const current = () => window.location.hash.replace(/^#\\/?/, "");

export default function App() {{
  const [route, setRoute] = useState(current());
  useEffect(() => {{
    const onHash = () => setRoute(current());
    window.addEventListener("hashchange", onHash);
    return () => window.removeEventListener("hashchange", onHash);
  }}, []);
  const Screen = routes[route] ?? routes[""];
  return <Screen />;
}}
"""
    out["src/main.jsx"] = """import React from "react";
import ReactDOM from "react-dom/client";
import App from "./App.jsx";

ReactDOM.createRoot(document.getElementById("root")).render(
  <React.StrictMode>
    <App />
  </React.StrictMode>
);
"""
    out["index.html"] = f"""<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>{doc.name}</title>
  {TAILWIND}
  </head>
  <body class="{BODY_CLASS}">
    <div id="root"></div>
{RUNTIME}
    <script type="module" src="/src/main.jsx"></script>
  </body>
</html>
"""
    out["vite.config.js"] = """import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";

export default defineConfig({ plugins: [react()] });
"""
    out["package.json"] = json.dumps({
        "name": app_name, "private": True, "version": "0.1.0", "type": "module",
        "scripts": {"dev": "vite", "build": "vite build", "preview": "vite preview"},
        "dependencies": {"react": "^18.3.1", "react-dom": "^18.3.1"},
        "devDependencies": {"@vitejs/plugin-react": "^4.3.1", "vite": "^5.4.0"},
    }, indent=2) + "\n"
    out["README.md"] = (f"# {doc.name}\n\nGenerated by Sketch2UI from a hand-drawn sketch.\n\n"
                        "```\nnpm install\nnpm run dev\n```\n")
    return {f"{app_name}/{k}": v for k, v in out.items()}


def to_zip(files: dict[str, str]) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for path, text in sorted(files.items()):
            z.writestr(path, text)
    return buf.getvalue()
