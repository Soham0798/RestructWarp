"""Step 29 (F4): every drawn form also gets a backend: table, validation and API routes.

Output (added to the export zip):
    backend/main.py, backend/requirements.txt   FastAPI + SQLite app, POST/GET /api/<form>
    frontend/*.html                             the pages, with forms posting JSON to that API
"""
import re

from app.schemas.component_schema import Component, UIDocument
from app.services.codegen_service import render_site

PY_TYPE = {"text": "str", "email": "EmailStr", "password": "str", "number": "float",
           "textarea": "str", "checkbox": "bool", "select": "str", "date": "date"}
COLUMN = {"text": "String(255)", "email": "String(255)", "password": "String(255)", "number": "Float",
          "textarea": "Text", "checkbox": "Boolean", "select": "String(255)", "date": "Date"}

SUBMIT_SCRIPT = """<script>
  // Sketch2UI: send each form to its generated API as JSON
  const API = "http://localhost:8000";
  document.querySelectorAll("form[data-endpoint]").forEach((form) => {
    form.addEventListener("submit", async (e) => {
      e.preventDefault();
      const data = {};
      for (const el of form.elements) {
        if (!el.name || !el.dataset.field) continue;
        data[el.dataset.field] = el.type === "checkbox" ? el.checked
          : el.type === "number" ? Number(el.value) : el.value;
      }
      const res = await fetch(API + form.dataset.endpoint, {
        method: "POST", headers: {"Content-Type": "application/json"}, body: JSON.stringify(data)});
      const status = form.querySelector("[data-status]") || form.appendChild(Object.assign(
        document.createElement("p"), {role: "status", className: "text-sm"}));
      status.dataset.status = "";
      status.textContent = res.ok ? "Saved!" : "Please check the fields and try again.";
    });
  });
</script>
"""


def class_name(form_name: str) -> str:
    return "".join(w.capitalize() for w in form_name.split("_")) + "Submission"


def forms_of(doc: UIDocument) -> list[Component]:
    found, names = [], set()
    for screen in doc.screens:
        for comp in screen.root.walk():
            if comp.form and comp.form.name not in names:
                names.add(comp.form.name)
                found.append(comp)
    return found


def backend_main(doc: UIDocument) -> str:
    models, schemas, routes = [], [], []
    for comp in forms_of(doc):
        f, cls = comp.form, class_name(comp.form.name)
        cols, ins, outs = [], [], []
        for fld in f.fields:
            nullable = "" if fld.required else ", nullable=True"
            col = "String(255)" if fld.type == "password" else COLUMN[fld.type]
            name = f"{fld.name}_hash" if fld.type == "password" else fld.name
            cols.append(f"    {name} = Column({col}{nullable})")
            t = PY_TYPE[fld.type]
            ins.append(f"    {fld.name}: {t}" if fld.required else f"    {fld.name}: Optional[{t}] = None")
            if fld.type != "password":  # never send passwords back
                outs.append(f"    {fld.name}: Optional[{t}] = None")
        models.append(f"class {cls}(Base):\n    __tablename__ = \"{f.name}_submissions\"\n"
                      f"    id = Column(Integer, primary_key=True)\n" + "\n".join(cols) +
                      "\n    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc))\n")
        schemas.append(f"class {cls}In(BaseModel):\n" + "\n".join(ins) +
                       f"\n\n\nclass {cls}Out(BaseModel):\n    model_config = ConfigDict(from_attributes=True)\n"
                       f"    id: int\n" + "\n".join(outs) + "\n")
        pw = [fld.name for fld in f.fields if fld.type == "password"]
        convert = "".join(f"    data[\"{p}_hash\"] = hash_password(data.pop(\"{p}\"))\n" for p in pw)
        routes.append(
            f"@app.post(\"/api/{f.name}\", response_model={cls}Out, status_code=201)\n"
            f"def create_{f.name}(body: {cls}In, db: Session = Depends(get_db)):\n"
            f"    data = body.model_dump()\n{convert}"
            f"    row = {cls}(**data)\n    db.add(row)\n    db.commit()\n    db.refresh(row)\n    return row\n\n\n"
            f"@app.get(\"/api/{f.name}\", response_model=list[{cls}Out])\n"
            f"def list_{f.name}(db: Session = Depends(get_db)):\n"
            f"    return db.query({cls}).order_by({cls}.id.desc()).limit(100).all()\n")

    return f'''"""Backend generated by Sketch2UI for "{doc.name}". Run: uvicorn main:app --reload"""
import hashlib
import os
from datetime import date, datetime, timezone
from typing import Optional

from fastapi import Depends, FastAPI
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, ConfigDict, EmailStr
from sqlalchemy import Boolean, Column, Date, DateTime, Float, Integer, String, Text, create_engine
from sqlalchemy.orm import Session, declarative_base, sessionmaker

engine = create_engine(os.getenv("DATABASE_URL", "sqlite:///./app.db"), connect_args={{"check_same_thread": False}})
SessionLocal = sessionmaker(bind=engine)
Base = declarative_base()


def get_db():
    db = SessionLocal()
    try:
        yield db
    finally:
        db.close()


def hash_password(password: str) -> str:
    salt = os.urandom(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, 200_000)
    return salt.hex() + ":" + digest.hex()


{chr(10).join(models)}

{chr(10).join(schemas)}

Base.metadata.create_all(engine)
app = FastAPI(title="{doc.name} API")
app.add_middleware(CORSMiddleware, allow_origins=os.getenv("FRONTEND_ORIGINS", "http://localhost:5500").split(","),
                   allow_methods=["*"], allow_headers=["*"])


{chr(10).join(routes)}'''


def wire_forms(html: str, doc: UIDocument) -> str:
    """Point each generated <form> at its endpoint and tag inputs with their field names."""
    for comp in forms_of(doc):
        label = comp.form.name.replace("_", " ")
        html = html.replace(f'aria-label="{label}"', f'aria-label="{label}" data-endpoint="/api/{comp.form.name}"')
        for fld in comp.form.fields:
            if fld.componentId:
                html = re.sub(rf'(name="{re.escape(fld.componentId)}")', rf'\1 data-field="{fld.name}"', html)
    if "data-endpoint" in html:
        html = html.replace("</body>", SUBMIT_SCRIPT + "</body>")
    return html


def build_fullstack(doc: UIDocument) -> dict[str, str]:
    files = {f"frontend/{name}": wire_forms(html, doc) for name, html in render_site(doc).items()}
    if forms_of(doc):
        files["backend/main.py"] = backend_main(doc)
        files["backend/requirements.txt"] = "fastapi\nuvicorn[standard]\nsqlalchemy\npydantic[email]\n"
        files["README.md"] = (f"# {doc.name}\n\nGenerated by Sketch2UI.\n\n"
                              "1. `cd backend && pip install -r requirements.txt && uvicorn main:app --reload`\n"
                              "2. Serve `frontend/` (e.g. VS Code Live Server on port 5500) and submit a form.\n")
    return files
